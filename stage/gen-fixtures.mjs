// Generate `stage/fixtures/*.json` from the REAL host service against a
// throwaway store, so the `status` half of every fixture is exactly what the
// bootstrap seeds (presets, overlays, practices, practiceInfo, stages) rather
// than a hand-typed copy that drifts. The `scorecard` half is the per-session
// view; its practice results and facts are the scenario and are authored here.
//
//   node stage/gen-fixtures.mjs      (after `npm run build`)
import { mkdtemp, mkdir, writeFile, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { SkillPresetsService } from '../lib/host/service.js'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(ROOT, 'stage', 'fixtures')
const NOW = new Date('2026-09-18T12:00:00Z')

const root = await mkdtemp(join(tmpdir(), 'skp-stage-'))
const service = new SkillPresetsService({ root: () => root, now: () => NOW })
await service.ensure()
const SESSION = 'stage-session'

/** One fixture: activate `preset` for the session, read status, attach the scenario's scorecard. */
async function fixture(name, { preset, scorecard }) {
  if (preset !== undefined) await service.activate(preset, 'user', { sessionId: SESSION })
  else await service.clearSession(SESSION)
  const status = { ...await service.status(), restrictSeam: false }
  const set = await service.setFor({ teamAttached: false, inGitRepo: true }, { id: SESSION })
  const resolved = await service.activeFor({ id: SESSION })
  const card = {
    sessionId: SESSION,
    live: true,
    experiments: [],
    strict: { enabled: false, seam: false, applied: false },
    stageGuess: { stage: 'plan', confidence: 0.5, why: ['nothing observed yet; defaulting to Plan'] },
    active: status.active,
    activePreset: set.preset,
    activeSource: resolved.source,
    agentPreset: 'standard',
    overlays: set.overlays,
    offered: set.skills.map(s => ({ name: s.name, via: s.via === 'preset' ? 'preset' : `overlay:${s.via.overlay}`, description: s.description })),
    unresolved: set.resolution.unresolved,
    practices: [],
    worst: 'n/a',
    summary: { sessionId: SESSION, preset: set.preset?.id ?? null, overlays: set.overlays, offered: set.skills.map(s => s.name), loaded: {}, unknown: [], practices: [], denied: 0, drift: [], suggestions: [], switches: [], loads: [], practiceTimeline: [], startedAt: NOW.toISOString(), lastAt: NOW.toISOString(), ...scorecard.summary },
    loadTrace: [],
    ...scorecard,
  }
  const doc = {
    $comment: `generated by stage/gen-fixtures.mjs — scenario "${name}"`,
    rpc: {
      status,
      scorecard: card,
      // Every READ the client half performs must answer, or the UI trips on
      // `undefined.length` and the stage tests a crash instead of a screen.
      // Empty-but-well-formed: the stage shows each surface's empty state.
      'library/list': { lock: status.lock, sources: status.sources },
      'usage/rollup': { version: 1, updatedAt: NOW.toISOString(), sessions: 0, skills: {}, presets: {}, practices: {}, unknownRequests: {}, coUsage: {}, byModel: {}, suggestions: { suggested: 0, accepted: 0, dismissed: 0, acceptMsSum: 0 } },
      'usage/recent': [],
      'placement/orphans': [],
      doctor: { findings: [], worst: 'ok', probedAt: NOW.toISOString() },
      'foundation/report': { diffs: [], updatable: 0, customized: 0, added: 0 },
      'pruning/report': { stale: [], missing: [], thresholds: { minSessions: 20, maxLoadRate: 0.1, minUnknown: 3 } },
      'knowledge/candidates': [],
      'teams/templates': { templates: [], agentTeamsPresent: false },
      'strict/presets': { shipped: ['standard', 'cordis', 'ptc'], strict: [] },
      lint: { byRef: {}, counts: { error: 0, warn: 0, info: 0 } },
      'impact/report': { skills: [], presets: [], sessions: 0 },
      'impact/session': { current: { sessions: 1, rated: 0 }, peers: { sessions: 0, rated: 0 }, peerCount: 0, preset: set.preset?.id ?? null },
      'experiments/aggregate': { results: [], pairs: [] },
      'experiments/compare': { cards: [] },
    },
  }
  await mkdir(OUT, { recursive: true })
  await writeFile(join(OUT, `${name}.json`), `${JSON.stringify(doc, null, 2)}\n`)
  console.log(`wrote stage/fixtures/${name}.json (${set.skills.length} skills, ${card.practices.length} practices)`)
}

